#!/usr/bin/env python3
"""Deterministically generate the large example's before/after Terraform configs.

The "after" world is written to main.tf and the "before" world to before.tf.txt.
generate.sh applies before, then plans after, producing a plan with a very wide,
several-layers-deep dependency graph and a ton of changes (create / replace /
delete / no-op) using only the hashicorp/random provider.

Run:  python3 gen_config.py   (then ../generate.sh large)
"""

# Layer sizes (number of distinct resource blocks per dependency layer).
LAYERS = [4, 18, 14, 9, 5]      # core backbone present in BOTH before & after
TYPES = ["random_pet", "random_string", "random_integer", "random_password",
         "random_id", "random_uuid"]


def value_args(rtype, bump=0):
    """Required/ForceNew args for a type. `bump` perturbs a ForceNew attr."""
    if rtype == "random_pet":
        return {"length": 2 + bump}
    if rtype == "random_string":
        return {"length": 16 + bump, "special": "false"}
    if rtype == "random_integer":
        return {"min": 1000, "max": 9000 + 500 * bump}
    if rtype == "random_password":
        return {"length": 24 + bump}
    if rtype == "random_id":
        return {"byte_length": 8 + bump}
    if rtype == "random_uuid":
        return {}
    return {}


def fmt_val(v):
    return v if isinstance(v, str) else str(v)


def emit(rtype, name, count, args, keepers):
    lines = [f'resource "{rtype}" "{name}" {{']
    if count is not None:
        lines.append(f"  count = {count}")
    for k, v in args.items():
        lines.append(f"  {k} = {fmt_val(v)}")
    if keepers:
        lines.append("  keepers = {")
        for k, v in keepers.items():
            lines.append(f'    {k} = {v}')
        lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n\n"


class Block:
    def __init__(self, layer, idx, gidx):
        self.layer = layer
        self.rtype = TYPES[gidx % len(TYPES)]
        self.name = f"n{layer}_{idx}"
        self.gidx = gidx

    @property
    def ref(self):
        # every random resource exposes an `id` attribute
        return f"{self.rtype}.{self.name}[0].id"


def build():
    core = []          # list of layers, each a list of Block
    gidx = 0
    for layer, size in enumerate(LAYERS):
        row = []
        for i in range(size):
            row.append(Block(layer, i, gidx))
            gidx += 1
        core.append(row)

    def deps_for(layer, i):
        """Pick two anchor blocks from the previous layer for graph edges."""
        prev = core[layer - 1]
        a = prev[i % len(prev)]
        b = prev[(i * 2 + 1) % len(prev)]
        out = {a.name: a}
        out[b.name] = b
        return list(out.values())

    def render_world(after):
        chunks = []
        # Layer 0 — stable seeds (identical in both worlds → no-op).
        for blk in core[0]:
            chunks.append(emit(blk.rtype, blk.name, 2, value_args(blk.rtype), {}))

        for layer in range(1, len(LAYERS)):
            for i, blk in enumerate(core[layer]):
                keepers = {}
                for d in deps_for(layer, i):
                    keepers[d.name] = d.ref
                args = value_args(blk.rtype)
                count = 4 + (blk.gidx % 6)        # 4..9 instances per block

                rule = blk.gidx % 6
                if rule in (2, 3):
                    # own replace via a rotation keeper bump
                    keepers["rotation"] = '"v2"' if after else '"v1"'
                elif rule == 4 and after:
                    count += 3                      # count grows in after  -> creates
                elif rule == 5 and after:
                    count = max(2, count - 2)       # count shrinks in after -> deletes
                # rule 0,1 -> stable (action comes only from dependency cascade)
                chunks.append(emit(blk.rtype, blk.name, count, args, keepers))

        # create-only blocks (after world): pure creates, anchored to core.
        if after:
            for j in range(8):
                layer = 1 + (j % 3)
                anchor = core[layer - 1][j % len(core[layer - 1])]
                rtype = TYPES[(j + 2) % len(TYPES)]
                chunks.append(emit(rtype, f"added_{j}", 3 + (j % 4),
                                   value_args(rtype), {anchor.name: anchor.ref}))
        # delete-only blocks (before world): pure deletes, anchored to core.
        else:
            for j in range(6):
                layer = 1 + (j % 3)
                anchor = core[layer - 1][j % len(core[layer - 1])]
                rtype = TYPES[(j + 1) % len(TYPES)]
                chunks.append(emit(rtype, f"legacy_{j}", 4 + (j % 3),
                                   value_args(rtype), {anchor.name: anchor.ref}))
        return "".join(chunks)

    header = ("# GENERATED by gen_config.py — do not edit by hand.\n"
              "# A very wide, multi-layer dependency graph with many changes.\n\n")
    with open("main.tf", "w") as f:
        f.write(header.replace("GENERATED", "GENERATED (after world)"))
        f.write(render_world(after=True))
    with open("before.tf.txt", "w") as f:
        f.write(header.replace("GENERATED", "GENERATED (before world)"))
        f.write(render_world(after=False))

    total = sum(LAYERS) + 8
    print(f"wrote main.tf and before.tf.txt: {sum(LAYERS)} core blocks across "
          f"{len(LAYERS)} layers (+create/delete-only)")


if __name__ == "__main__":
    build()
